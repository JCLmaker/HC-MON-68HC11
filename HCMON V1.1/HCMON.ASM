	STAA	SYSFLG
	STAB	RXDATA		;1 BYTE BUFFER
EXIT1:	RTI

;CTRL/T GIBT IM LAUFENDEN USER-PROGRAMM ALLE CPU-REGISTER AUS

CTRLTI:	LDAA	SYSFLG
	BITA	#%01000000	;CTRL/C GESPERRT?
	BNE	SAVECH		;JA, DANN KEIN STATUS ANZEIGEN!
	BITA	#%10000000	;AUTO-BREAKPOINT BEI TRACE AKTIV?
	BNE	SHOWIT		;JA, DANN IST CTRL/T AKTIV!
	BITA	#%00010010	;SINGLE-STEP ODER NORMALER TRACE?
	BNE	EXIT1		;JA: DANN KEIN CTRL/T SINNVOLL !
SHOWIT:	INS			;STACK KORRIGIEREN
	TSX			;	UND USER STACKPOINTER RETTEN
	XGDX			;USER-SP ZEIGT NUN AUF DIE
	ADDD	#8		;	ADRESSE VOR DEM INTERRUPT !
	STD	SPH		;USER-SP SPEICHERN
	JSR	OUTCL		;IM LAUFENDEN USER-PROGRAMM
	JSR	USRREG		;ALLE CPU-REGISTER AUSGEBEN
	RTI

;AUSWERTUNG DES ABBRUCHZEICHENS CTRL/C

EXIT2:	BITA	#%01000000	;CTRL/C GESPERRT?
	BNE	SAVECH		;JA, DANN PROGRAMM NICHT ABBRECHEN
	BITA	#%00000001	;USER MODE GESETZT ?
	BNE	ABORT1		;JA:	 USERPROGRAMM ABBRECHEN
EXIT2A:	JMP	CONTRL		;NEIN: ABBRUCH EINES HAUPTKOMMANDOS

EXIT2B:	PULA
	ORAA	#%00000100	;CTRL/C-FLAG SETZEN
	STAA	SYSFLG		;CTRL/C-EINGABE MERKEN!
	RTI

;ABBRUCH EINES USER-PROGRAMMS

ABORT1:	BITA	#%10000000	;AUTO-BREAKPOINT BEI TRACE AKTIV?
	BNE	 BRKIT		;JA, DANN IST CTRL/C AKTIV!
	BITA	 #%00000010	;TRACE MODE GESETZT?
	BNE	 EXIT2B 	;JA...
	BITA	 #%00010000	;SINGLE STEP MODE GESETZT?
	BNE	 EXIT2A 	;JA...
BRKIT:	TSX			;USER STACKPOINTER RETTEN
	XGDX			;USER-SP ZEIGT NUN AUF DIE
	ADDD	 #9		;  ADRESSE VOR DEM INTERRUPT !
	STD	 SPH		;USER-SP SPEICHERN
	XGDX
	LDAA	 SYSFLG
	BITA	 #%10000000	;AUTO-BREAK MODE?
	BEQ	 SUMONI 	;NEIN...
	LDX	 AUTOBK 	;AUTO-BREAKPOINT-ADRESSE LADEN
	LDAA	 AUTOOP 	;    UND ALTEN OPCODE
	STAA	 ,X		;	WIEDER SETZEN
SUMONI:	LDS	 #STACK 	;MONITOR STACK SETZEN
	CLI			;INTERRUPT WIEDER FREIGEBEN
CTRLCA:	CLR	 SYSFLG 	;SYSTEM NEU INITIALISIEREN
	LDX	 #CTRLCM	;ABBRUCHMELDUNG AUSGEBEN
