	LDAA	SYSFLG
	ORAA	#%00000010	;TRACE BIT
	STAA	SYSFLG		;    SETZEN
	CLI
	LDX	#TXTTRC
	BRA	G0

GOTO:	LDX	#TXTGOT
G0:	JSR	OUTSTR
	JSR	INP4HX		;STARTADRESSE HOLEN
	BCC	G1
	CMPB	#CR		;LETZTE USER-ADRESSE IM PC VERWENDEN?
	BNE	GOABOR
	LDAA	SYSFLG
	BITA	#%00000010	;TRACE BIT GESETZT?
	BNE	G0A		; JA...
	JSR	OUTCL		;NUR BEI G-BEFEHL NEUE ZEILE ANFANGEN
G0A:	LDX	SPH
	DEX			;X ZEIGT AUF USER-PCH
	BRA	G2		;MIT ALTEM PC WEITERMACHEN...

GOABOR:	LDX	#CHRERR
	JMP	OUTSTR

G1:	LDX	SPH
	DEX			;X ZEIGT AUF USER-PCH
	LDD	IOWH		;STARTADRESSE NOCHEINMAL LADEN
	STD	,X		; UND IN USER-PC SCHREIBEN
	SUBD	,X		;VERGLEICH: "CMPD ,X" SP IN RAM ?
	BEQ	G2
	LDX	#GOERR
	JMP	OUTSTR

G2:	XGDX
	SUBD	#$7		;AUF USER-F ZEIGEN
	XGDX			;X = START-SP DES USERS (ZEIGT AUF FLAGS)
	LDAA	SYSFLG
	BITA	#%00010010	;SINGLE STEP ODER TRACE?
	BNE	G2C		; JA...
	JMP	G3

G2C:	JSR	OUTCL		;JA: NEUE ZEILE ANFANGEN
	JSR	PSOPC		;JA: CPU-REGISTER UND NAECHSTEN OPCODE ANZEIGEN
