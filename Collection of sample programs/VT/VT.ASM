	INCLUDE	EQUS.INC
	INCLUDE	VT100.INC

	ORG	$E0

BUFFER:	DS	$F		;BUFFER FUER CURSOR-POSITION

	ORG	$6000

START:	LDS	#$6F00
	JSR	INIT_SCREEN

MAIN:	LDX	#TEXT
	JSR	PRINT
	JSR	TERINP

	JSR	SCREEN2
	JSR	INPWOR
	JSR	SCREEN1

	BRA	MAIN

TEXT:	DB	'IM ERSTEN FENSTER',$0A,$0D,0

	;SCREEN 1 EINSCHALTEN
SCREEN1:
	LDX	#?TEXT
	JSR	PRINT
	LDX	#BUFFER-1
SCR12:	INX
	JSR	TERINP
	STAA	,X
	CMPA	#'R'
	BNE	SCR12
	INX
	CLRA
	STAA	,X

	SCROLL	'03','13'
	RESTORE

	RTS

?TEXT:	DB	$1B,'[','6','n',0

	;SCREEN 2 EINSCHALTEN
SCREEN2:
	SAVE
	SCROLL	'15','24'
	LDX	#BUFFER-1
SCR22:	INX
	LDAA	,X
	CMPA	#'R'
	BNE	SCR22
	LDAA	#'H'
	STAA	,X

	LDX	#BUFFER
	JSR	PRINT

	RTS

	;BILDSCHIRM INITIALISIEREN
INIT_SCREEN:
	CLS
	LDX	#UEBER
	JSR	PRINT

CUR1:	CURSOR	'02','01'

	LDAB	#80
	LDAA	#'-'
?LOOP:	JSR	TEROUT
	DECB
	BNE	?LOOP

CUR2:	CURSOR	'14','01'

	LDAB	#80
	LDAA	#'-'
?LOOP:	JSR	TEROUT
	DECB
	BNE	?LOOP

	SCROLL	'03','13'

	CURSOR	'03','01'

	LDD	#$1B5B
	STD	BUFFER
	LDD	#$3135
	STD	BUFFER+2
	LDD	#$3B31
	STD	BUFFER+4
	LDD	#$5200
	STD	BUFFER+6

	RTS

UEBER:	DB	'*** BETRIEBSPROGRAMM FUER DIE LINKADAPTER-KARTE ***',0

	END
